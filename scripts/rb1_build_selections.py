#!/usr/bin/env python3
"""Build the derived document selections campaign rb1 needs beyond the frozen split sets.

The frozen split (``config/splits/runbook-v1``) has one id file per set. R15 (plan finding 7,
decision 5) scores the input-cap sweep on the long documents of dev and the rotation pool: every
dev or pool document whose length band (``assignments.jsonl`` ``band``) is above ``<=4k``. This
script derives that selection from the committed ``assignments.jsonl`` and writes it under
``config/splits/rb1/`` as an id list and its exclusion complement, the form run specs select with
(``dataset.exclude_ids_file`` + ``draw: ranked``). Held-out and calibration ids never enter it.
It also copies the split's ``heldout.ids`` next to them, so the preflight held-out seal
(``mailroom_sandbox.heldout_seal.leak_errors``, which reads ``heldout.ids`` beside the exclusion
file) checks the rb1 draws too.

    python scripts/rb1_build_selections.py           # write
    python scripts/rb1_build_selections.py --check   # exit 1 when a committed file differs
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPLIT = ROOT / "config" / "splits" / "runbook-v1"
OUT = ROOT / "config" / "splits" / "rb1"

#: Sets R15 may draw from; held-out and calibration are never selected.
R15_SETS = ("dev", "pool")
SHORT_BAND = "<=4k"


def assignments() -> list[dict]:
    with (SPLIT / "assignments.jsonl").open(encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def r15_long_ids(rows: list[dict] | None = None) -> list[str]:
    """Dev and pool documents over 4k tokens (bands <=16k, <=32k, >32k), sorted."""
    rows = assignments() if rows is None else rows
    return sorted(r["id"] for r in rows if r["set"] in R15_SETS and r["band"] != SHORT_BAND)


def render() -> dict[str, str]:
    rows = assignments()
    keep = r15_long_ids(rows)
    keep_set = set(keep)
    rest = sorted(r["id"] for r in rows if r["id"] not in keep_set)
    head = ("# rb1 R15 long-document selection: dev + rotation-pool documents above the <=4k band\n"
            "# Generated by `python scripts/rb1_build_selections.py` from config/splits/runbook-v1/assignments.jsonl;\n"
            "# do not hand-edit.\n")
    heldout = (SPLIT / "heldout.ids").read_text(encoding="utf-8")
    return {
        "heldout.ids": ("# rb1 copy of config/splits/runbook-v1/heldout.ids, for the preflight held-out seal\n"
                        "# Generated by `python scripts/rb1_build_selections.py`; do not hand-edit.\n" + heldout),
        "r15-long.ids": head + "".join(f"{i}\n" for i in keep),
        "r15-long.exclude.ids": head.replace("selection:", "selection (complement):", 1) + "".join(f"{i}\n" for i in rest),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="compare with the committed files; write nothing")
    args = parser.parse_args()
    stale = []
    for name, text in render().items():
        path = OUT / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print(f"stale: {', '.join(stale)} (run python scripts/rb1_build_selections.py)", file=sys.stderr)
        return 1
    print(f"{'checked' if args.check else 'wrote'} {OUT.relative_to(ROOT)}: r15-long {len(r15_long_ids())} ids")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
