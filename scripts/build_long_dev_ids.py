#!/usr/bin/env python3
"""Build the long-document dev list for the Phase 5 part 2 sorter check (``p5-s2-head-sorter-{off,on}``).

The runbook-v2 split bands stop at ``>32k``, so no existing list selects the documents
``job.long_document_head`` cuts (over ``merger_reads.HEAD_THRESHOLD`` characters). This builder reads
the pinned corpus (``corpus.load_hf_rows``: the same default + ground_truth join a run draws, at
``FAMILY_HF_REVISION``) and writes, under ``config/splits/runbook-v2/``:

* ``dev-long.ids``: the dev documents whose ``doc_text`` is over the threshold;
* ``dev-long.exclude.ids``: every other corpus document (``dataset.exclude_ids_file`` with ``split: all``);
* ``dev-long.json``: the revision, the threshold and each listed document's character count.

    python scripts/build_long_dev_ids.py            # write
    python scripts/build_long_dev_ids.py --check    # exit 1 on drift

LOCAL ONLY: it reads the pinned parquet from the Hugging Face cache (offline; ``HF_HUB_OFFLINE=1`` is
set unless already set), which CI does not hold. Only dev documents are read; the held-out set never is.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPLIT = ROOT / "config" / "splits" / "runbook-v2"
REPO = "Lucius-Morningstar/mailroom-dataset"


def _read_ids(path: Path) -> list[str]:
    return [s for line in path.read_text(encoding="utf-8").splitlines() if (s := line.strip()) and not s.startswith("#")]


def build() -> dict[str, str]:
    """``{file name: content}`` for the three files."""
    from mailroom_sandbox import corpus, merger_reads
    from mailroom_sandbox.job.spec import FAMILY_HF_REVISION, DatasetSpec

    dev = set(_read_ids(SPLIT / "dev.ids"))
    universe = dev | set(_read_ids(SPLIT / "dev.exclude.ids"))
    spec = DatasetSpec(provider="huggingface", repo=REPO, config="ground_truth", split="all",
                       revision=FAMILY_HF_REVISION)
    rows = corpus.load_hf_rows(spec)
    ids = {str(r.get("document_id") or r.get("id")) for r in rows}
    if ids != universe:
        raise SystemExit(f"the pinned corpus ({len(ids)} ids) is not the runbook-v2 universe ({len(universe)} ids)")
    threshold = merger_reads.HEAD_THRESHOLD
    chars, classes = {}, Counter()
    for r in rows:
        doc_id = str(r.get("document_id") or r.get("id"))
        if doc_id in dev and len(r.get("doc_text") or "") > threshold:
            chars[doc_id] = len(r["doc_text"])
            classes[str(r.get("expected"))] += 1
    long_ids = sorted(chars)
    head = "# Generated by `python scripts/build_long_dev_ids.py`; do not hand-edit.\n"
    manifest = {"builder": "scripts/build_long_dev_ids.py", "revision": FAMILY_HF_REVISION, "threshold": threshold,
                "source": "config/splits/runbook-v2/dev.ids", "counts": dict(sorted(classes.items())),
                "chars": {k: chars[k] for k in long_ids}}
    return {
        "dev-long.ids": f"# dev-long: {len(long_ids)} dev documents over {threshold} characters\n" + head
                        + "".join(f"{i}\n" for i in long_ids),
        "dev-long.exclude.ids": "# complement of dev-long: use as dataset.exclude_ids_file with split: all\n" + head
                                + "".join(f"{i}\n" for i in sorted(universe - set(long_ids))),
        "dev-long.json": json.dumps(manifest, indent=2, sort_keys=True) + "\n",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when a committed file differs")
    args = parser.parse_args(argv)
    os.environ.setdefault("HF_HUB_OFFLINE", "1")
    files = build()
    if args.check:
        drift = [n for n, text in files.items()
                 if not (SPLIT / n).is_file() or (SPLIT / n).read_text(encoding="utf-8") != text]
        if drift:
            print(f"drift: {', '.join(drift)}; re-run python scripts/build_long_dev_ids.py", file=sys.stderr)
            return 1
        print("dev-long lists match the pinned corpus")
        return 0
    for name, text in files.items():
        (SPLIT / name).write_text(text, encoding="utf-8")
    print(f"wrote {', '.join(files)} under {SPLIT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
