#!/usr/bin/env python3
"""Build a split's exposure list: the production tuning list plus every document an
earlier split's runs have already shown a model.

``sandbox splits build --exposure <file>`` keeps held-out away from the ids in
``<file>``. When a campaign moves to a new split (runbook-v1 on dataset v9.1 to
runbook-v2 on v9.3), the documents its earlier looks drew must stay out of the new
held-out set too, or a sealed set would hold documents already scored. The list is the
sorted union of:

* ``--base``: an id list (``#`` comments allowed), normally
  ``config/production/excluded-ids.txt``;
* ``--add``: more id lists, such as the old split's spent looks;
* ``--add-ids-in``: committed run artifacts (CSV, JSONL), whose ``DOC-<16 hex>`` ids are
  collected. Use it for documents a run drew outside a look file (a hand-check sheet, a
  20-document smoke).

The header names every source and its id count, so ``--check`` (exit 1 on drift) needs
only committed files and runs offline in CI. Campaign rb1, runbook-v2::

    python scripts/build_split_exposure.py \\
        --base config/production/excluded-ids.txt \\
        --add config/splits/runbook-v1/dev-look1.ids \\
        --add config/splits/rb1-r13b/formcal-draw1.ids \\
        --add-ids-in reports/campaigns/rb1/rb1-r02-scorer-handcheck/rb1-r02.cases.jsonl \\
        --add-ids-in reports/campaigns/rb1/rb1-r13b-sorter-vs-decision/rb1-r13b-smoke20-decision-sorter-luna/i01/outputs/rb1-r13b-smoke20-decision-sorter-luna-i01.item-scores.csv \\
        --add-ids-in reports/campaigns/rb1/rb1-r13b-sorter-vs-decision/rb1-r13b-smoke20-llm-sorter-qwen3.7-flash/i01/outputs/rb1-r13b-smoke20-llm-sorter-qwen3.7-flash-i01.item-scores.csv \\
        --out config/splits/runbook-v2-exposure.txt

Append ``--check`` to the same command to verify the committed file.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC_ID = re.compile(r"\bDOC-[0-9a-f]{16}\b")


def _id_list(path: Path) -> set[str]:
    ids = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            ids.add(line)
    return ids


def _rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def build(base: Path, add: list[Path], add_ids_in: list[Path]) -> str:
    sources: list[tuple[str, str, int]] = []
    ids: set[str] = set()
    for kind, paths, read in (("base", [base], _id_list), ("add", add, _id_list),
                              ("ids-in", add_ids_in, lambda p: set(DOC_ID.findall(p.read_text(encoding="utf-8"))))):
        for p in paths:
            if not p.is_file():
                raise SystemExit(f"build_split_exposure: {p} does not exist")
            got = read(p)
            if not got:
                raise SystemExit(f"build_split_exposure: {p} holds no document ids")
            sources.append((kind, _rel(p), len(got)))
            ids |= got
    head = [
        "# Split exposure list: held-out avoids these documents (sandbox splits build --exposure).",
        "# Generated by scripts/build_split_exposure.py; do not hand-edit. Sources (kind, path, ids):",
        *(f"#   {kind} {path} {n}" for kind, path, n in sources),
        f"# {len(ids)} ids",
    ]
    return "\n".join([*head, *sorted(ids)]) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--base", type=Path, required=True)
    ap.add_argument("--add", type=Path, action="append", default=[])
    ap.add_argument("--add-ids-in", type=Path, action="append", default=[])
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--check", action="store_true", help="exit 1 if --out differs from a rebuild")
    args = ap.parse_args(argv)
    text = build(args.base, args.add, args.add_ids_in)
    if args.check:
        have = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        if have != text:
            print(f"{args.out}: stale; rerun without --check", file=sys.stderr)
            return 1
        print(f"{args.out}: up to date")
        return 0
    args.out.write_text(text, encoding="utf-8")
    n = sum(1 for line in text.splitlines() if not line.startswith("#"))
    print(f"wrote {args.out} ({n} ids)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
