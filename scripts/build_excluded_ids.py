#!/usr/bin/env python3
"""Build the committed held-out exclusion list from prompt-tuning runs.

Every document a tuning run scored is no longer held out, so the production
slice draw must skip it (``dataset.exclude_ids_file``). The list is the sorted
union of the ``id`` of each run's ``dataset.jsonl``; the header names every
source run and its row count::

    python scripts/build_excluded_ids.py --runs-dir <dir> [--runs-dir <dir2>] \\
        --run <run_id> [--run <run_id> ...] --out config/production/excluded-ids.txt
    python scripts/build_excluded_ids.py ... --check   # exit 1 on drift

Each ``--run`` resolves in the first ``--runs-dir`` that holds its
``dataset.jsonl``; run ids are the only source names written (no paths).
Repeated ``--run`` values are collapsed (first occurrence wins).

Regeneration and ``--check`` are LOCAL ONLY: the run datasets live in the
gitignored ``data/runtime/runs`` directories of the sibling checkouts, so CI
cannot run either. Two lists are committed (``<sandbox checkout>``, ``<rejudge-knob checkout>`` and
``<slice-gate checkout>`` are the local checkout roots).

``excluded-ids-ladder.txt`` is frozen. It holds the 11 ladder runs, and the correspondence v3 A/B
arms exclude it, so their own draw never changes::

    python3 scripts/build_excluded_ids.py --runs-dir <sandbox checkout>/data/runtime/runs --runs-dir <rejudge-knob checkout>/data/runtime/runs --runs-dir <slice-gate checkout>/data/runtime/runs --run pipeline-qwen-flash-25 --run pipeline-qwen-flash-25-fit --run pipeline-qwen-flash-25-fit-r2 --run pipeline-qwen-flash-25-fit-r3 --run pipeline-qwen-flash-25-e1-contract-control --run pipeline-qwen-flash-25-e1-contract-chunk --run pipeline-qwen-flash-25-e2-corporate-control --run pipeline-qwen-flash-25-e2-corporate-judge --run pipeline-qwen-flash-25-e2-corporate-rejudge --run pipeline-qwen-flash-25-e3-mix-control --run pipeline-qwen-flash-25-e3-chunk-judge-all --out config/production/excluded-ids-ladder.txt

``excluded-ids.txt`` is the production slices' list. It holds the ladder runs plus every later tuning
run, currently the v3 A/B, whose two arms share one draw. Append each new tuning run here before the
next slice launches::

    python3 scripts/build_excluded_ids.py --runs-dir <sandbox checkout>/data/runtime/runs --runs-dir <rejudge-knob checkout>/data/runtime/runs --runs-dir <slice-gate checkout>/data/runtime/runs --run pipeline-qwen-flash-25 --run pipeline-qwen-flash-25-fit --run pipeline-qwen-flash-25-fit-r2 --run pipeline-qwen-flash-25-fit-r3 --run pipeline-qwen-flash-25-e1-contract-control --run pipeline-qwen-flash-25-e1-contract-chunk --run pipeline-qwen-flash-25-e2-corporate-control --run pipeline-qwen-flash-25-e2-corporate-judge --run pipeline-qwen-flash-25-e2-corporate-rejudge --run pipeline-qwen-flash-25-e3-mix-control --run pipeline-qwen-flash-25-e3-chunk-judge-all --run specialist-condensed-v3-correspondence-qwen-v2arm --out config/production/excluded-ids.txt

Append ``--check`` to the same command to verify the committed file.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HEADER_TITLE = (
    "# Held-out exclusion list: documents already used for prompt tuning.\n"
    "# Generated by scripts/build_excluded_ids.py; do not hand-edit.\n"
    "# Regenerate: see scripts/build_excluded_ids.py docstring\n"
    "# Scope: documents used to tune extraction and routing (the pipeline runs listed below).\n"
    "# Sorter prompt tuning drew from the sorter handoff's train split (2,979 of 3,302 documents),\n"
    "# so sorter-tuning documents are NOT excluded and sorter accuracy measured on production\n"
    "# slices is in-sample. See docs/runbooks/production-slices.md.\n"
    "# Sources (run id: dataset.jsonl rows):"
)


def read_ids(run_dir: Path) -> list[str]:
    """Every row ``id`` of ``<run_dir>/dataset.jsonl`` (JSONL read line by line)."""
    path = Path(run_dir) / "dataset.jsonl"
    ids: list[str] = []
    with path.open(encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
                ids.append(str(row["id"]))
            except (ValueError, KeyError, TypeError) as exc:
                raise SystemExit(f"{path}:{lineno}: malformed row ({exc!r}); need a JSON object with an 'id'") from exc
    return ids


def _rows_noun(n: int) -> str:
    return "row" if n == 1 else "rows"


def render(run_dirs: list[Path]) -> str:
    """The full file text: header naming each source run, then one id per line."""
    lines = [HEADER_TITLE]
    unique: set[str] = set()
    for d in run_dirs:
        ids = read_ids(d)
        unique.update(ids)
        lines.append(f"# {Path(d).name}: {len(ids)} {_rows_noun(len(ids))}")
    lines.append(f"# Unique ids: {len(unique)}")
    return "\n".join([*lines, *sorted(unique)]) + "\n"


def build(run_dirs: list[Path]) -> list[str]:
    """Sorted unique ids across the runs' datasets."""
    return sorted({i for d in run_dirs for i in read_ids(d)})


def resolve_runs(runs_dirs: list[Path], run_ids: list[str]) -> list[Path]:
    """Map each run id to its directory in the first runs dir that has a dataset."""
    out: list[Path] = []
    for run_id in dict.fromkeys(run_ids):
        for root in runs_dirs:
            if (Path(root) / run_id / "dataset.jsonl").is_file():
                out.append(Path(root) / run_id)
                break
        else:
            raise SystemExit(f"run {run_id!r} has no dataset.jsonl in any --runs-dir")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs-dir", action="append", type=Path, required=True, help="runs root (repeatable)")
    ap.add_argument("--run", action="append", required=True, help="run id (repeatable)")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--check", action="store_true", help="exit 1 when --out differs from a rebuild")
    args = ap.parse_args(argv)

    text = render(resolve_runs(args.runs_dir, args.run))
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else None
        if current != text:
            print(f"{args.out} is out of date; rebuild without --check", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
